function beautyAdvice(type) {
  if (type === "acne")
    return "Use salicylic acid facewash + oil-free moisturizer.";
  if (type === "dry")
    return "Hydrating cleanser + hyaluronic serum works best.";
  if (type === "pigmentation")
    return "Vitamin C + sunscreen daily is recommended.";
  return "Tell me your skin concern.";
}